MULTI_CHAR_SURNAMES = [
    "欧阳", "歐陽", "司马", "司馬", "上官", "诸葛", "諸葛", "东方", "東方",
    "西门", "西門", "令狐", "皇甫", "公孙", "公孫", "慕容", "司徒", "宇文",
]


def surname_of(author_name: str) -> str:
    name = (author_name or "").strip()
    for multi in MULTI_CHAR_SURNAMES:
        if name.startswith(multi):
            return multi
    return name[:1] if name else ""


def stroke_count(author_name: str, variant: str = "simplified") -> tuple[int, bool]:
    """返回 (笔画数, 是否命中表格)；未命中时用一个较大占位值排到最后"""
    surname = surname_of(author_name)
    table = TRADITIONAL_STROKES if variant == "traditional" else SIMPLIFIED_STROKES
    if surname in table:
        return table[surname], True
    fallback_table = SIMPLIFIED_STROKES if variant == "traditional" else TRADITIONAL_STROKES
    if surname in fallback_table:
        return fallback_table[surname], True
    return 999, False
